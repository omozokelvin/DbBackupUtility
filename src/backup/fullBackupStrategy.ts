import * as fs from 'fs';
import * as path from 'path';
import archiver from 'archiver';
import {
  BackupStrategy,
  BackupConfig,
  BackupResult,
  DatabaseType,
  BackupType,
  Connector,
  BackupLogger,
  Notifier,
} from '../types';

export class FullBackupStrategy implements BackupStrategy {
  private logger: BackupLogger;
  private notifier?: Notifier;

  constructor(logger: BackupLogger, notifier?: Notifier) {
    this.logger = logger;
    this.notifier = notifier;
  }

  async backup(config: BackupConfig): Promise<BackupResult> {
    const result: BackupResult = {
      id: config.id,
      name: config.name,
      status: 'running',
      startTime: new Date(),
    };

    try {
      this.logger.info(`Starting full backup for database: ${config.name}`, {
        database: config.name,
        type: config.connection.type,
        backupType: config.backupType,
      });

      const connector = this.createConnector(config.connection);
      await connector.connect(config.connection);

      const tables = await connector.getTables();
      const collections = await connector.getCollections();

      const backupDir = path.join(
        config.outputPath || process.cwd(),
        'backups',
        config.name,
      );
      if (!fs.existsSync(backupDir)) {
        fs.mkdirSync(backupDir, { recursive: true });
      }

      const timestamp = Date.now();
      const fileName = `${config.name}_${config.connection.type}_${timestamp}`;
      const filePath = path.join(backupDir, `${fileName}.sql`);

      await this.exportDatabase(connector, config, filePath, tables, collections);

      let finalPath = filePath;

      if (config.compression) {
        const compressedPath = await this.compressFile(filePath, backupDir, fileName);
        fs.unlinkSync(filePath);
        finalPath = compressedPath;
      } else {
        finalPath = filePath;
      }

      const fileSize = fs.statSync(finalPath).size;
      const compressionRatio = config.compression
        ? this.calculateCompressionRatio(fileSize, fs.statSync(filePath).size)
        : 0;

      result.status = 'completed';
      result.endTime = new Date();
      result.filePath = finalPath;
      result.fileSize = fileSize;
      result.compressionRatio = compressionRatio;
      result.tables = tables;
      result.collections = collections;
      result.recordsBackedUp = await this.countRecords(connector, tables, collections);
      result.duration = result.endTime.getTime() - result.startTime.getTime();

      this.logger.info(`Full backup completed successfully`, {
        backupId: result.id,
        filePath: result.filePath,
        fileSize: result.fileSize,
        duration: result.duration,
      });

      if (this.notifier) {
        await this.notifier.send(result);
      }

      return result;
    } catch (error) {
      result.status = 'failed';
      result.endTime = new Date();
      result.error = (error as Error).message;
      result.duration = result.endTime.getTime() - result.startTime.getTime();

      this.logger.error(`Full backup failed: ${(error as Error).message}`, {
        backupId: result.id,
        error: result.error,
      });

      if (this.notifier) {
        await this.notifier.send(result);
      }

      return result;
    }
  }

  validateBackupType(dbType: DatabaseType, backupType: BackupType): boolean {
    return backupType === 'full';
  }

  private createConnector(type: string): import('../types').Connector {
    const { ConnectorFactory } = require('../connectors/connectorFactory');
    return ConnectorFactory.createConnector(type as DatabaseType);
  }

  private async exportDatabase(
    connector: import('../types').Connector,
    config: BackupConfig,
    filePath: string,
    tables: string[],
    collections: string[],
  ): Promise<void> {
    const output = fs.createWriteStream(filePath);
    const schema = await this.generateSchema(connector, config, tables, collections);

    output.write(schema);
    output.end();

    await new Promise<void>((resolve, reject) => {
      output.on('finish', () => resolve());
      output.on('error', (err) => reject(err));
    });
  }

  private async generateSchema(
    connector: import('../types').Connector,
    config: BackupConfig,
    tables: string[],
    collections: string[],
  ): Promise<string> {
    let schema = `-- Database Backup\n`;
    schema += `-- Database Type: ${config.connection.type}\n`;
    schema += `-- Database Name: ${config.name}\n`;
    schema += `-- Backup Timestamp: ${new Date().toISOString()}\n`;
    schema += `-- Backup Type: ${config.backupType}\n`;
    schema += `-- Generated by DB Backup Utility\n\n`;

    const metadata = await connector.getMetadata();
    schema += `-- Metadata: ${JSON.stringify(metadata, null, 2)}\n\n`;

    if (config.connection.type === 'sqlite') {
      schema += await this.generateSqliteSchema(connector as any, tables);
    } else if (config.connection.type === 'mysql') {
      schema += await this.generateMySQLSchema(connector as any, tables);
    } else if (config.connection.type === 'postgresql') {
      schema += await this.generatePostgreSQLSchema(connector as any, tables);
    } else if (config.connection.type === 'mongodb') {
      schema += await this.generateMongoDBDump(connector as any, collections);
    }

    return schema;
  }

  private async generateSqliteSchema(
    connector: any,
    tables: string[],
  ): Promise<string> {
    let schema = '-- SQLite Schema\n';
    const db = connector.db;

    for (const table of tables) {
      const createStatement = db.prepare(`SELECT sql FROM sqlite_master WHERE type='table' AND name='${table}'`).get() as { sql: string };
      if (createStatement?.sql) {
        schema += `${createStatement.sql};\n\n`;
      }
    }

    return schema;
  }

  private async generateMySQLSchema(connector: any, tables: string[]): Promise<string> {
    let schema = '-- MySQL Schema\n';
    const pool = connector.pool;

    for (const table of tables) {
      const [rows] = await pool.query(`SHOW CREATE TABLE \`${table}\``);
      const createStatement = (rows as { 'Create Table': string }[])[0];
      schema += `${createStatement['Create Table']};\n\n`;
    }

    return schema;
  }

  private async generatePostgreSQLSchema(connector: any, tables: string[]): Promise<string> {
    let schema = '-- PostgreSQL Schema\n';
    const client = connector.client;

    for (const table of tables) {
      const result = await client.query(
        `SELECT pg_get_constraintdef(oid) as constraint_def, contype as constraint_type 
         FROM pg_constraint WHERE conrelid = ${client.escapeIdentifier(table)}::regclass`,
      );
      schema += `-- Table: ${table}\n`;
      for (const row of result.rows) {
        schema += `${row.constraint_def};\n`;
      }
      schema += '\n';
    }

    return schema;
  }

  private async generateMongoDBDump(connector: any, collections: string[]): Promise<string> {
    let dump = '-- MongoDB Dump\n';
    const db = connector.db;

    for (const collectionName of collections) {
      const collection = db.collection(collectionName);
      const documents = await collection.find({}).toArray();

      dump += `// Collection: ${collectionName} (${documents.length} documents)\n`;
      dump += `JSON: ${JSON.stringify(documents, null, 2)}\n\n`;
    }

    return dump;
  }

  private async countRecords(
    connector: import('../types').Connector,
    tables: string[],
    collections: string[],
  ): Promise<number> {
    const stats = await connector.getDatabaseStats();
    return stats.totalRecords;
  }

  private async compressFile(
    filePath: string,
    backupDir: string,
    fileName: string,
  ): Promise<string> {
    const compressedPath = path.join(backupDir, `${fileName}.tar.gz`);
    const output = fs.createWriteStream(compressedPath);

    return new Promise<void>((resolve, reject) => {
      const archive = archiver('tar', { gzip: true, gzipOptions: { level: 9 } });

      archive.on('error', (err) => reject(err));
      archive.on('finish', () => resolve());

      archive.pipe(output);
      archive.file(filePath, { name: `${path.basename(filePath)}` });
      archive.finalize();
    });
  }

  private calculateCompressionRatio(originalSize: number, compressedSize: number): number {
    if (originalSize === 0) return 0;
    return ((originalSize - compressedSize) / originalSize) * 100;
  }
}
